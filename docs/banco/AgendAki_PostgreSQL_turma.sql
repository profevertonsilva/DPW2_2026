-- AgendAki - Estrutura PostgreSQL baseada nos modelos conceitual e logico 2.0
-- Data: 2026-10-23
-- Codificacao do arquivo: UTF-8.
--
-- EXECUCAO
-- 1. Crie/selecione um banco vazio, por exemplo: agendaki.
-- 2. O servidor precisa ter o PostGIS instalado. A extensao e habilitada abaixo;
--    a conta que executar o script precisa de permissao para essa operacao.
-- 3. Execute o arquivo inteiro no Query Tool do pgAdmin ou com:
--      psql -U postgres -d agendaki -v ON_ERROR_STOP=1 -f AgendAki_PostgreSQL.sql
-- O script cria a estrutura no schema public. Nao apaga tabelas ou dados.
-- Execute uma unica vez em um banco sem as tabelas deste projeto.
--
-- DECISOES DE CONVERSAO DO DER
-- a) Foram preservadas as 18 entidades e seus atributos de negocio.
--    Nomes foram padronizados em minusculas, com FKs no formato entidade_id.
-- b) estabelecimento recebeu o id que aparece no conceitual, mas falta no logico;
--    login_papel recebeu o id que tambem aparece apenas no conceitual.
--    telefone.telefone_PK passou a se chamar telefone.id.
--    cliente_estabelecimento, pacote e servico_atendimento usam PKs compostas.
-- c) FKs invertidas/ausentes no logico foram reposicionadas: login_papel aponta
--    para login e papel_plataforma; estabelecimento para categoria; telefone e
--    horario_funcionamento para estabelecimento; vinculo_estabelecimento para
--    profissional e estabelecimento; bloqueio_horario para o vinculo; servico
--    para estabelecimento; atendimento para cliente_estabelecimento e vinculo;
--    auditoria para profissional e estabelecimento. avaliacao aponta para
--    atendimento, com UNIQUE para permitir no maximo uma avaliacao por atendimento.
--    Nao foram mantidas as antigas FKs no lado inverso desses relacionamentos.
-- d) VACHAR foi corrigido para VARCHAR; TIMESTAMPZ para TIMESTAMPTZ.
--    Instantes de data/hora foram uniformizados como TIMESTAMPTZ.
--    dia_semana foi convertido de TIMESTAMP para SMALLINT (0=domingo a 6=sabado).
--    reserva_expira_em passou de TIME para TIMESTAMPTZ, pois representa uma expiracao.
--    Tipos incompletos: complemento VARCHAR(255), profissional.telefone VARCHAR(15),
--    profissional.cpf VARCHAR(14) e atendimento.valor_final NUMERIC(10,2).
-- e) POSTGIS() nao e um tipo SQL: localizacao usa geography(Point,4326), com
--    longitude/latitude em WGS84 e indice espacial GiST.
-- f) pacote e servico_atendimento estao desenhadas com os mesmos relacionamentos:
--    cada registro referencia um atendimento e um servico, contendo o valor.
--    Ambas foram preservadas separadamente. Nao foi inventado um catalogo de
--    pacotes reutilizaveis ou uma composicao de pacotes, ausentes no DER.
-- g) NOT NULL e DEFAULT foram definidos para identificadores, relacionamentos
--    obrigatorios e campos essenciais. Descricoes, fotos e eventos opcionais
--    aceitam NULL. Essas escolhas completam o DER, que nao detalha a nulabilidade.
--    Campos com dominio a/i explicito usam CHECK; os demais status mantem o
--    tamanho indicado, sem inventar uma lista de valores. A escala de nota e
--    a unicidade de CPF/email nao foram impostas porque nao constam do DER.
-- h) usuario_responsavel referencia profissional.id conforme a ligacao no DER.
--    entidade_afetada foi mantida como INTEGER, sem FK, por nao haver alvo unico.
--    O campo recorrencia foi preservado em cliente, sem reinterpretar seu escopo.
--
-- ESCOPO
-- FKs garantem a existencia dos registros relacionados; as FKs compostas de
-- atendimento tambem garantem cliente e profissional no mesmo estabelecimento.
-- A aplicacao deve validar que o servico escolhido pertence ao estabelecimento
-- do atendimento, controlar sobreposicao de horarios e manter atualizado_em/
-- data_atualizacao nos UPDATEs. DEFAULT CURRENT_TIMESTAMP atua apenas no INSERT.
-- A participacao minima 1..N do pai (por exemplo, ter ao menos um horario) deve
-- ser garantida no fluxo de cadastro; uma FK sozinha nao exige filhos existentes.
-- Nao ha triggers, dados de exemplo ou tabelas adicionais do framework.
--
-- Referencias tecnicas:
-- https://www.postgresql.org/docs/current/ddl-constraints.html
-- https://postgis.net/docs/using_postgis_dbmanagement.html#PostGIS_Geography

BEGIN;

SET LOCAL search_path TO public;

CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA public;

-- 01. Credenciais e informacoes de acesso.
CREATE TABLE login (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acesso TIMESTAMPTZ,
    senha_hash TEXT NOT NULL,
    tipo_usuario VARCHAR(100) NOT NULL,
    status CHAR(1) NOT NULL DEFAULT 'a',
    data_atualizacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_login PRIMARY KEY (id),
    CONSTRAINT ck_login_status CHECK (status IN ('a', 'i'))
);

-- 02. Papeis disponiveis na plataforma.
CREATE TABLE papel_plataforma (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(30) NOT NULL,
    descricao TEXT,
    CONSTRAINT pk_papel_plataforma PRIMARY KEY (id)
);

-- 03. Atribuicao de papeis a contas de acesso.
-- atribuido_por foi interpretado como o login que realizou a atribuicao;
-- pode ser NULL para atribuicoes iniciais/automaticas.
CREATE TABLE login_papel (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    login_id INTEGER NOT NULL,
    papel_plataforma_id INTEGER NOT NULL,
    atribuido_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(15) NOT NULL,
    atribuido_por INTEGER,
    CONSTRAINT pk_login_papel PRIMARY KEY (id),
    CONSTRAINT uq_login_papel UNIQUE (login_id, papel_plataforma_id),
    CONSTRAINT fk_login_papel_login FOREIGN KEY (login_id)
        REFERENCES login (id),
    CONSTRAINT fk_login_papel_papel FOREIGN KEY (papel_plataforma_id)
        REFERENCES papel_plataforma (id),
    CONSTRAINT fk_login_papel_autor FOREIGN KEY (atribuido_por)
        REFERENCES login (id)
);

-- 04. Perfil profissional; uma conta pode estar associada a mais de um perfil.
CREATE TABLE profissional (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    telefone VARCHAR(15),
    email VARCHAR(150) NOT NULL,
    cpf VARCHAR(14),
    status CHAR(1) NOT NULL,
    foto_perfil VARCHAR(255),
    login_id INTEGER NOT NULL,
    CONSTRAINT pk_profissional PRIMARY KEY (id),
    CONSTRAINT fk_profissional_login FOREIGN KEY (login_id)
        REFERENCES login (id)
);

-- 05. Perfil de cliente.
CREATE TABLE cliente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    telefone VARCHAR(15),
    email VARCHAR(150) NOT NULL,
    cpf VARCHAR(14),
    foto_perfil VARCHAR(255),
    recorrencia INTEGER,
    login_id INTEGER NOT NULL,
    CONSTRAINT pk_cliente PRIMARY KEY (id),
    CONSTRAINT fk_cliente_login FOREIGN KEY (login_id)
        REFERENCES login (id)
);

-- 06. Categorias dos estabelecimentos.
CREATE TABLE categoria_estabelecimento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    status CHAR(1) NOT NULL DEFAULT 'a',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_categoria_estabelecimento PRIMARY KEY (id),
    CONSTRAINT ck_categoria_status CHECK (status IN ('a', 'i'))
);

-- 07. Dados e localizacao do estabelecimento.
CREATE TABLE estabelecimento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    categoria_estabelecimento_id INTEGER NOT NULL,
    cep VARCHAR(9),
    estado CHAR(2),
    cidade VARCHAR(50),
    bairro VARCHAR(50),
    logradouro VARCHAR(100),
    numero INTEGER,
    complemento VARCHAR(255),
    localizacao GEOGRAPHY(POINT, 4326),
    status CHAR(1) NOT NULL DEFAULT 'a',
    antecedencia_lembrete_minutos INTEGER,
    cobranca_antecipada BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_estabelecimento PRIMARY KEY (id),
    CONSTRAINT fk_estabelecimento_categoria FOREIGN KEY (categoria_estabelecimento_id)
        REFERENCES categoria_estabelecimento (id),
    CONSTRAINT ck_estabelecimento_status CHECK (status IN ('a', 'i')),
    CONSTRAINT ck_estabelecimento_lembrete
        CHECK (antecedencia_lembrete_minutos >= 0)
);

-- 08. Telefones: um estabelecimento pode possuir varios numeros.
CREATE TABLE telefone (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    estabelecimento_id INTEGER NOT NULL,
    telefone VARCHAR(15) NOT NULL,
    CONSTRAINT pk_telefone PRIMARY KEY (id),
    CONSTRAINT fk_telefone_estabelecimento FOREIGN KEY (estabelecimento_id)
        REFERENCES estabelecimento (id)
);

-- 09. Horarios semanais de funcionamento.
-- Permite mais de um intervalo no mesmo dia, por exemplo, manha e tarde.
-- Um fechamento menor que a abertura pode representar um periodo que vira o dia.
CREATE TABLE horario_funcionamento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    estabelecimento_id INTEGER NOT NULL,
    dia_semana SMALLINT NOT NULL,
    aberto BOOLEAN NOT NULL,
    hora_abertura TIME,
    hora_fechamento TIME,
    CONSTRAINT pk_horario_funcionamento PRIMARY KEY (id),
    CONSTRAINT fk_horario_estabelecimento FOREIGN KEY (estabelecimento_id)
        REFERENCES estabelecimento (id),
    CONSTRAINT ck_horario_dia_semana CHECK (dia_semana BETWEEN 0 AND 6),
    CONSTRAINT ck_horario_aberto CHECK (
        NOT aberto OR (hora_abertura IS NOT NULL AND hora_fechamento IS NOT NULL)
    )
);

-- 10. Associacao de profissionais com estabelecimentos.
-- A chave auxiliar (id, estabelecimento_id) suporta a FK composta de atendimento.
CREATE TABLE vinculo_estabelecimento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    profissional_id INTEGER NOT NULL,
    estabelecimento_id INTEGER NOT NULL,
    status CHAR(1) NOT NULL DEFAULT 'a',
    vinculado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    desvinculado_em TIMESTAMPTZ,
    CONSTRAINT pk_vinculo_estabelecimento PRIMARY KEY (id),
    CONSTRAINT uq_vinculo_id_estabelecimento UNIQUE (id, estabelecimento_id),
    CONSTRAINT fk_vinculo_profissional FOREIGN KEY (profissional_id)
        REFERENCES profissional (id),
    CONSTRAINT fk_vinculo_estabelecimento FOREIGN KEY (estabelecimento_id)
        REFERENCES estabelecimento (id),
    CONSTRAINT ck_vinculo_status CHECK (status IN ('a', 'i')),
    CONSTRAINT ck_vinculo_periodo CHECK (desvinculado_em >= vinculado_em)
);

-- 11. Cadastro do cliente em cada estabelecimento.
CREATE TABLE cliente_estabelecimento (
    cliente_id INTEGER NOT NULL,
    estabelecimento_id INTEGER NOT NULL,
    CONSTRAINT pk_cliente_estabelecimento PRIMARY KEY (cliente_id, estabelecimento_id),
    CONSTRAINT fk_cliente_estabelecimento_cliente FOREIGN KEY (cliente_id)
        REFERENCES cliente (id),
    CONSTRAINT fk_cliente_estabelecimento_local FOREIGN KEY (estabelecimento_id)
        REFERENCES estabelecimento (id)
);

-- 12. Periodos bloqueados na agenda de um vinculo profissional.
CREATE TABLE bloqueio_horario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    vinculo_estabelecimento_id INTEGER NOT NULL,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    motivo TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_bloqueio_horario PRIMARY KEY (id),
    CONSTRAINT fk_bloqueio_vinculo FOREIGN KEY (vinculo_estabelecimento_id)
        REFERENCES vinculo_estabelecimento (id),
    CONSTRAINT ck_bloqueio_periodo CHECK (fim > inicio)
);

-- 13. Catalogo de servicos oferecidos pelo estabelecimento.
CREATE TABLE servico (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    estabelecimento_id INTEGER NOT NULL,
    nome VARCHAR(255) NOT NULL,
    descricao TEXT,
    duracao_minutos INTEGER NOT NULL,
    status CHAR(1) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_servico PRIMARY KEY (id),
    CONSTRAINT fk_servico_estabelecimento FOREIGN KEY (estabelecimento_id)
        REFERENCES estabelecimento (id),
    CONSTRAINT ck_servico_duracao CHECK (duracao_minutos > 0)
);

-- 14. Agendamento/atendimento de um cliente por um profissional.
-- cliente_id e estabelecimento_id tambem representam o relacionamento com
-- cliente_estabelecimento; nao e necessario um identificador artificial na associacao.
CREATE TABLE atendimento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cliente_id INTEGER NOT NULL,
    estabelecimento_id INTEGER NOT NULL,
    vinculo_estabelecimento_id INTEGER NOT NULL,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    valor_final NUMERIC(10, 2),
    reserva_expira_em TIMESTAMPTZ,
    presenca_confirmada_em TIMESTAMPTZ,
    cancelada_em TIMESTAMPTZ,
    motivo_cancelamento TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(50) NOT NULL DEFAULT 'reservado',
    CONSTRAINT pk_atendimento PRIMARY KEY (id),
    CONSTRAINT fk_atendimento_estabelecimento FOREIGN KEY (estabelecimento_id)
        REFERENCES estabelecimento (id),
    CONSTRAINT fk_atendimento_cliente_local FOREIGN KEY (cliente_id, estabelecimento_id)
        REFERENCES cliente_estabelecimento (cliente_id, estabelecimento_id),
    CONSTRAINT fk_atendimento_vinculo_local
        FOREIGN KEY (vinculo_estabelecimento_id, estabelecimento_id)
        REFERENCES vinculo_estabelecimento (id, estabelecimento_id),
    CONSTRAINT ck_atendimento_periodo CHECK (fim > inicio),
    CONSTRAINT ck_atendimento_valor CHECK (valor_final >= 0),
    CONSTRAINT ck_atendimento_status CHECK (status IN (
        'reservado',
        'agendado',
        'aguardando confirmacao',
        'confirmado',
        'realizado',
        'cancelado',
        'expirado',
        'não compareceu'
    ))
);

-- 15. Servicos de um atendimento e os respectivos valores.
CREATE TABLE servico_atendimento (
    atendimento_id INTEGER NOT NULL,
    servico_id INTEGER NOT NULL,
    valor NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_servico_atendimento PRIMARY KEY (atendimento_id, servico_id),
    CONSTRAINT fk_servico_atendimento_atendimento FOREIGN KEY (atendimento_id)
        REFERENCES atendimento (id),
    CONSTRAINT fk_servico_atendimento_servico FOREIGN KEY (servico_id)
        REFERENCES servico (id),
    CONSTRAINT ck_servico_atendimento_valor CHECK (valor >= 0)
);

-- 16. Associacao denominada pacote no DER, preservada conforme desenhada.
CREATE TABLE pacote (
    atendimento_id INTEGER NOT NULL,
    servico_id INTEGER NOT NULL,
    valor NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_pacote PRIMARY KEY (atendimento_id, servico_id),
    CONSTRAINT fk_pacote_atendimento FOREIGN KEY (atendimento_id)
        REFERENCES atendimento (id),
    CONSTRAINT fk_pacote_servico FOREIGN KEY (servico_id)
        REFERENCES servico (id),
    CONSTRAINT ck_pacote_valor CHECK (valor >= 0)
);

-- 17. Avaliacao opcional e unica de cada atendimento.
CREATE TABLE avaliacao (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    atendimento_id INTEGER NOT NULL,
    nota INTEGER NOT NULL,
    comentario TEXT,
    status VARCHAR(1) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_avaliacao PRIMARY KEY (id),
    CONSTRAINT uq_avaliacao_atendimento UNIQUE (atendimento_id),
    CONSTRAINT fk_avaliacao_atendimento FOREIGN KEY (atendimento_id)
        REFERENCES atendimento (id)
);

-- 18. Historico de operacoes, ligado ao profissional e estabelecimento.
CREATE TABLE auditoria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    usuario_responsavel INTEGER NOT NULL,
    estabelecimento_id INTEGER NOT NULL,
    tipo_operacao VARCHAR(30) NOT NULL,
    entidade_afetada INTEGER NOT NULL,
    valor_anterior TEXT,
    valor_novo TEXT,
    data_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_auditoria PRIMARY KEY (id),
    CONSTRAINT fk_auditoria_responsavel FOREIGN KEY (usuario_responsavel)
        REFERENCES profissional (id),
    CONSTRAINT fk_auditoria_estabelecimento FOREIGN KEY (estabelecimento_id)
        REFERENCES estabelecimento (id)
);

-- Indices de apoio. PK e UNIQUE ja criam seus proprios indices.
CREATE INDEX idx_login_papel_papel ON login_papel (papel_plataforma_id);
CREATE INDEX idx_login_papel_autor ON login_papel (atribuido_por);
CREATE INDEX idx_profissional_login ON profissional (login_id);
CREATE INDEX idx_cliente_login ON cliente (login_id);
CREATE INDEX idx_estabelecimento_categoria ON estabelecimento (categoria_estabelecimento_id);
CREATE INDEX idx_estabelecimento_localizacao ON estabelecimento USING GIST (localizacao);
CREATE INDEX idx_telefone_estabelecimento ON telefone (estabelecimento_id);
CREATE INDEX idx_horario_estabelecimento_dia ON horario_funcionamento (estabelecimento_id, dia_semana);
CREATE INDEX idx_vinculo_profissional ON vinculo_estabelecimento (profissional_id);
CREATE INDEX idx_vinculo_estabelecimento ON vinculo_estabelecimento (estabelecimento_id);
CREATE INDEX idx_cliente_estabelecimento_local ON cliente_estabelecimento (estabelecimento_id);
CREATE INDEX idx_bloqueio_vinculo_inicio ON bloqueio_horario (vinculo_estabelecimento_id, inicio);
CREATE INDEX idx_servico_estabelecimento ON servico (estabelecimento_id);
CREATE INDEX idx_atendimento_estabelecimento_inicio ON atendimento (estabelecimento_id, inicio);
CREATE INDEX idx_atendimento_cliente_local ON atendimento (cliente_id, estabelecimento_id);
CREATE INDEX idx_atendimento_vinculo_local ON atendimento (vinculo_estabelecimento_id, estabelecimento_id);
CREATE INDEX idx_servico_atendimento_servico ON servico_atendimento (servico_id);
CREATE INDEX idx_pacote_servico ON pacote (servico_id);
CREATE INDEX idx_auditoria_responsavel ON auditoria (usuario_responsavel);
CREATE INDEX idx_auditoria_estabelecimento_data ON auditoria (estabelecimento_id, data_hora);

COMMIT;
